/** Maps OC UI user types to SCENARIOS_BY_USER_TYPE keys. */
export const OC_SCENARIO_KEYS = {
  NDA: "nda",
  ARMY: "army",
  NAVY: "navy",
  AIRFORCE: "air_force",
  PTSD: "terror_survivor",
  NAVY_PTSD: "terror_survivor",
};

function resolveScenarioKey(userType) {
  if (!userType) return "army";
  return OC_SCENARIO_KEYS[userType] || userType;
}

export function getOcScenarios(userType) {
  const key = resolveScenarioKey(userType);
  return SCENARIOS_BY_USER_TYPE[key] || SCENARIOS_BY_USER_TYPE.army;
}

export function getOcInstructions(userType) {
  const key = resolveScenarioKey(userType);
  return key === "terror_survivor" ? INSTRUCTIONS_WELLBEING : INSTRUCTIONS_DEFENCE;
}
